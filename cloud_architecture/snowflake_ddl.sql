-- ==============================================================================
-- Snowflake Production DDL for ConstructRec Data Warehouse
-- Targets: DPR Construction & vConstruct Analytics Layer
-- ==============================================================================

USE ROLE ACCOUNTADMIN;
CREATE WAREHOUSE IF NOT EXISTS CONSTRUCTREC_WH 
  WITH WAREHOUSE_SIZE = 'X-SMALL' 
  AUTO_SUSPEND = 180 
  AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS DPR_CONSTRUCTION_DWH;
CREATE SCHEMA IF NOT EXISTS DPR_CONSTRUCTION_DWH.SILVER;
CREATE SCHEMA IF NOT EXISTS DPR_CONSTRUCTION_DWH.GOLD;

USE SCHEMA DPR_CONSTRUCTION_DWH.GOLD;

-- Dimension: Subcontractors
CREATE OR REPLACE TABLE DIM_SUBCONTRACTORS (
    SUBCONTRACTOR_ID VARCHAR(30) PRIMARY KEY,
    COMPANY_NAME VARCHAR(255) NOT NULL,
    TRADE VARCHAR(100) NOT NULL,
    PRIMARY_LOCATION VARCHAR(100) NOT NULL,
    SAFETY_EMR NUMBER(4, 2) NOT NULL,
    BONDING_CAPACITY_USD NUMBER(18, 2),
    EXPERIENCE_YEARS INT,
    ACTIVE_CREW_COUNT INT,
    CERTIFICATIONS_STR VARCHAR(500),
    SPECIALTIES_STR VARCHAR(500),
    SAFETY_TIER VARCHAR(50),
    IS_SAFETY_COMPLIANT BOOLEAN,
    IS_ACTIVE BOOLEAN
) CLUSTER BY (TRADE, PRIMARY_LOCATION);

-- Dimension: Projects
CREATE OR REPLACE TABLE DIM_PROJECTS (
    PROJECT_ID VARCHAR(30) PRIMARY KEY,
    PROJECT_NAME VARCHAR(255) NOT NULL,
    SECTOR VARCHAR(100) NOT NULL,
    LOCATION VARCHAR(100) NOT NULL,
    BUDGET_USD NUMBER(18, 2),
    BUDGET_MILLIONS NUMBER(10, 2),
    SQ_FOOTAGE INT,
    REQUIRED_TRADE VARCHAR(100),
    BIM_LOD_REQUIRED VARCHAR(50),
    STRICT_SAFETY_MANDATE BOOLEAN,
    STATUS VARCHAR(50)
) CLUSTER BY (SECTOR, LOCATION);

-- Fact: Project Evaluations
CREATE OR REPLACE TABLE FCT_PROJECT_EVALUATIONS (
    EVALUATION_ID VARCHAR(30) PRIMARY KEY,
    PROJECT_ID VARCHAR(30) REFERENCES DIM_PROJECTS(PROJECT_ID),
    SUBCONTRACTOR_ID VARCHAR(30) REFERENCES DIM_SUBCONTRACTORS(SUBCONTRACTOR_ID),
    RATING NUMBER(3, 1) NOT NULL,
    SCHEDULE_SCORE NUMBER(3, 1),
    SAFETY_SCORE NUMBER(3, 1),
    CHANGE_ORDER_RATE NUMBER(5, 3),
    RECOMMENDATION_CONFIRMED BOOLEAN,
    EVALUATION_TIMESTAMP TIMESTAMP_NTZ
) CLUSTER BY (EVALUATION_TIMESTAMP);

-- Analytical ML Feature Store Mart
CREATE OR REPLACE TABLE FEATURES_RECOMMENDER_MART AS
WITH SUB_STATS AS (
    SELECT 
        SUBCONTRACTOR_ID,
        COUNT(EVALUATION_ID) AS RATING_COUNT,
        ROUND(AVG(RATING), 2) AS AVG_RATING,
        ROUND(AVG(SCHEDULE_SCORE), 2) AS AVG_SCHEDULE_SCORE,
        ROUND(AVG(SAFETY_SCORE), 2) AS AVG_SAFETY_SCORE,
        ROUND(AVG(CHANGE_ORDER_RATE), 3) AS AVG_CHANGE_ORDER_RATE
    FROM FCT_PROJECT_EVALUATIONS
    GROUP BY SUBCONTRACTOR_ID
)
SELECT 
    S.SUBCONTRACTOR_ID,
    S.COMPANY_NAME,
    S.TRADE,
    S.PRIMARY_LOCATION,
    S.SAFETY_EMR,
    S.BONDING_CAPACITY_USD,
    S.EXPERIENCE_YEARS,
    S.ACTIVE_CREW_COUNT,
    S.CERTIFICATIONS_STR,
    S.SAFETY_TIER,
    S.IS_SAFETY_COMPLIANT,
    COALESCE(ST.RATING_COUNT, 0) AS RATING_COUNT,
    COALESCE(ST.AVG_RATING, 3.8) AS AVG_RATING,
    COALESCE(ST.AVG_SCHEDULE_SCORE, 3.8) AS AVG_SCHEDULE_SCORE,
    COALESCE(ST.AVG_SAFETY_SCORE, 3.8) AS AVG_SAFETY_SCORE,
    -- Bayesian Adjusted Score in Snowflake SQL
    ROUND(
        (COALESCE(ST.RATING_COUNT, 0) * COALESCE(ST.AVG_RATING, 3.8) + 5.0 * 3.8) 
        / (COALESCE(ST.RATING_COUNT, 0) + 5.0),
        2
    ) AS BAYESIAN_RATING
FROM DIM_SUBCONTRACTORS S
LEFT JOIN SUB_STATS ST ON S.SUBCONTRACTOR_ID = ST.SUBCONTRACTOR_ID;
